import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Sunset palette, shared with the Android onboarding colors.
SUN_TOP = "#FFD23F"
SUN_MID = "#FF4F6D"
SUN_BOTTOM = "#7A2CF5"
SHADOW = "#3B1470"
TEXT_LIGHT = "#FFFFFF"
ICON_BG_TOP = "#2A1052"
ICON_BG_BOTTOM = "#0E0820"

# 5x7 block font, only the letters needed.
GLYPHS = {
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "L": ["10000", "10000", "10000", "10000", "10000", "10000", "11111"],
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "Y": ["10001", "10001", "01010", "00100", "00100", "00100", "00100"],
    "R": ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    "E": ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    "T": ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    "O": ["01110", "10001", "10001", "10001", "10001", "10001", "01110"],
}


def play_triangle(rows):
    """Cells of a pixelated play triangle pointing right, 'rows' tall (odd)."""
    return [(col, row) for row in range(rows) for col in range(min(row, rows - 1 - row) + 1)]


def text_cells(word, origin_x=0, origin_y=0):
    cells = []
    for index, letter in enumerate(word):
        for row, line in enumerate(GLYPHS[letter]):
            for col, bit in enumerate(line):
                if bit == "1":
                    cells.append((origin_x + index * 6 + col, origin_y + row))
    return cells


def path_data(cells, x0, y0, size, inset, fmt="{:.2f}"):
    """One path with a square per cell; 'inset' leaves a gap that gives the pixel look."""
    f = lambda v: fmt.format(v).rstrip("0").rstrip(".")
    side = size - inset
    parts = []
    for col, row in cells:
        x = x0 + col * size + inset / 2
        y = y0 + row * size + inset / 2
        parts.append(f"M{f(x)},{f(y)}h{f(side)}v{f(side)}h-{f(side)}z")
    return "".join(parts)


# Splash layout in cells: triangle (17 rows, 9 cols), 3 cells of space, then two text lines.
TRI_ROWS = 17
TEXT_X = 9 + 3
PLAY_CELLS = text_cells("PLAY", TEXT_X, 0)
RETRO_CELLS = text_cells("RETRO", TEXT_X, 10)
TRI_CELLS = play_triangle(TRI_ROWS)


def write(relative_path, content, mode="w"):
    path = os.path.join(ROOT, relative_path)
    with open(path, mode, **({} if "b" in mode else {"encoding": "utf-8", "newline": "\n"})) as f:
        f.write(content)
    print("wrote", relative_path)


def splash_svg():
    width, height = 1280, 720
    cols, rows = TEXT_X + 29, TRI_ROWS
    cell = 28
    x0 = (width - cols * cell) / 2
    y0 = (height - rows * cell) / 2
    inset = 3
    shadow = cell * 0.3
    # The text block (16 rows) is centered against the 17 rows tall triangle.
    text_y0 = y0 + cell * 0.5
    gradient_y1 = y0
    gradient_y2 = y0 + rows * cell

    def p(cells, ox, oy):
        return path_data(cells, ox, oy, cell, inset)

    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- PlayRetro splash logo. Generated by tools/branding/generate_branding.py, do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
  <defs>
    <linearGradient id="sunset" gradientUnits="userSpaceOnUse" x1="0" y1="{gradient_y1}" x2="0" y2="{gradient_y2}">
      <stop offset="0" stop-color="{SUN_TOP}"/>
      <stop offset="0.5" stop-color="{SUN_MID}"/>
      <stop offset="1" stop-color="{SUN_BOTTOM}"/>
    </linearGradient>
  </defs>
  <g fill="{SHADOW}">
    <path d="{p(TRI_CELLS, x0 + shadow, y0 + shadow)}"/>
    <path d="{p(PLAY_CELLS + RETRO_CELLS, x0 + shadow, text_y0 + shadow)}"/>
  </g>
  <path fill="url(#sunset)" d="{p(TRI_CELLS, x0, y0)}"/>
  <path fill="{TEXT_LIGHT}" d="{p(PLAY_CELLS, x0, text_y0)}"/>
  <path fill="url(#sunset)" d="{p(RETRO_CELLS, x0, text_y0)}"/>
</svg>
"""


# Launcher icon: 108dp viewport, the triangle stays inside the 66dp safe zone.
ICON_ROWS = 17
ICON_CELL = 3.2
ICON_INSET = 0.7


def icon_origin():
    tri_w, tri_h = (ICON_ROWS // 2 + 1) * ICON_CELL, ICON_ROWS * ICON_CELL
    # Shift right a little so the triangle looks optically centered.
    return (108 - tri_w) / 2 + 2.5, (108 - tri_h) / 2


def icon_foreground():
    x0, y0 = icon_origin()
    shadow = ICON_CELL * 0.35
    cells = play_triangle(ICON_ROWS)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- PlayRetro launcher mark. Generated by tools/branding/generate_branding.py, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{SHADOW}"
        android:pathData="{path_data(cells, x0 + shadow, y0 + shadow, ICON_CELL, ICON_INSET)}" />
    <path android:pathData="{path_data(cells, x0, y0, ICON_CELL, ICON_INSET)}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="{y0:.2f}"
                android:endX="0"
                android:endY="{y0 + ICON_ROWS * ICON_CELL:.2f}">
                <item android:color="{SUN_TOP.replace('#', '#FF')}" android:offset="0" />
                <item android:color="{SUN_MID.replace('#', '#FF')}" android:offset="0.5" />
                <item android:color="{SUN_BOTTOM.replace('#', '#FF')}" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""


def icon_monochrome():
    x0, y0 = icon_origin()
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- PlayRetro themed icon mark. Generated by tools/branding/generate_branding.py, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{path_data(play_triangle(ICON_ROWS), x0, y0, ICON_CELL, ICON_INSET)}" />
</vector>
"""


def icon_background():
    # Dark sky with faint scanlines for a CRT feel.
    scanlines = "".join(f"M0,{y}h108v1h-108z" for y in range(2, 108, 4))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- PlayRetro launcher background. Generated by tools/branding/generate_branding.py, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="0"
                android:endY="108"
                android:startColor="{ICON_BG_TOP.replace('#', '#FF')}"
                android:endColor="{ICON_BG_BOTTOM.replace('#', '#FF')}" />
        </aapt:attr>
    </path>
    <path
        android:fillColor="#14000000"
        android:pathData="{scanlines}" />
</vector>
"""


def desktop_icon_svg():
    x0, y0 = icon_origin()
    shadow = ICON_CELL * 0.35
    cells = play_triangle(ICON_ROWS)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Play Retro desktop icon. Generated by tools/branding/generate_branding.py, do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="256" height="256" viewBox="0 0 108 108">
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{ICON_BG_TOP}"/>
      <stop offset="1" stop-color="{ICON_BG_BOTTOM}"/>
    </linearGradient>
    <linearGradient id="sunset" gradientUnits="userSpaceOnUse" x1="0" y1="{y0:.2f}" x2="0" y2="{y0 + ICON_ROWS * ICON_CELL:.2f}">
      <stop offset="0" stop-color="{SUN_TOP}"/>
      <stop offset="0.5" stop-color="{SUN_MID}"/>
      <stop offset="1" stop-color="{SUN_BOTTOM}"/>
    </linearGradient>
  </defs>
  <rect width="108" height="108" rx="20" fill="url(#sky)"/>
  <path fill="{SHADOW}" d="{path_data(cells, x0 + shadow, y0 + shadow, ICON_CELL, ICON_INSET)}"/>
  <path fill="url(#sunset)" d="{path_data(cells, x0, y0, ICON_CELL, ICON_INSET)}"/>
</svg>
"""


def raster_icon(size):
    from PIL import Image, ImageDraw

    def hex_rgb(value):
        return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5))

    def lerp(a, b, t):
        return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

    scale = size / 108
    image = Image.new("RGBA", (size, size))
    draw = ImageDraw.Draw(image)
    top, bottom = hex_rgb(ICON_BG_TOP), hex_rgb(ICON_BG_BOTTOM)
    for y in range(size):
        draw.line([(0, y), (size, y)], fill=lerp(top, bottom, y / (size - 1)))

    # Rounded square mask like a typical app icon.
    mask = Image.new("L", (size, size))
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius=round(size * 0.19), fill=255)

    x0, y0 = icon_origin()
    cell = ICON_CELL * scale
    inset = ICON_INSET * scale
    tri_top, tri_bottom = y0 * scale, (y0 + ICON_ROWS * ICON_CELL) * scale
    stops = [hex_rgb(SUN_TOP), hex_rgb(SUN_MID), hex_rgb(SUN_BOTTOM)]

    def sunset(y):
        t = min(max((y - tri_top) / (tri_bottom - tri_top), 0.0), 1.0)
        return lerp(stops[0], stops[1], t * 2) if t < 0.5 else lerp(stops[1], stops[2], t * 2 - 1)

    for offset, shadow in ((ICON_CELL * 0.35 * scale, True), (0.0, False)):
        for col, row in play_triangle(ICON_ROWS):
            x = x0 * scale + col * cell + inset / 2 + offset
            y = y0 * scale + row * cell + inset / 2 + offset
            color = hex_rgb(SHADOW) if shadow else sunset(y + cell / 2)
            draw.rectangle([x, y, x + cell - inset, y + cell - inset], fill=color)

    image.putalpha(mask)
    return image


def raster_icons():
    try:
        import PIL  # noqa: F401
    except ImportError:
        print("Pillow not installed, skipping the PNG, ICO and ICNS icons")
        return
    raster_icon(256).save(os.path.join(ROOT, "resources/graphics/window_icon_256.png"))
    print("wrote resources/graphics/window_icon_256.png")
    large = raster_icon(1024)
    large.save(os.path.join(ROOT, "es-app/assets/PlayRetro.ico"),
               sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    print("wrote es-app/assets/PlayRetro.ico")
    large.save(os.path.join(ROOT, "es-app/assets/PlayRetro.icns"))
    print("wrote es-app/assets/PlayRetro.icns")


if __name__ == "__main__":
    write("resources/graphics/splash.svg", splash_svg())
    drawable = "android/app/src/main/res/drawable/"
    write(drawable + "ic_launcher_foreground.xml", icon_foreground())
    write(drawable + "ic_launcher_monochrome.xml", icon_monochrome())
    write(drawable + "ic_launcher_background.xml", icon_background())
    write("es-app/assets/org.play_retro.frontend.svg", desktop_icon_svg())
    raster_icons()
